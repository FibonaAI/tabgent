"""Fork a legacy transcript at a visible message without modifying its source."""
import json
import tempfile
from pathlib import Path


def fork(session, message_id, edit=False):
    thread = session.rpc('thread/read', {
        'threadId': session.thread['id'], 'includeTurns': True,
    })['thread']
    if thread.get('status', {}).get('type') == 'active':
        raise ValueError('Wait for the current reply to finish first')
    messages = [item for turn in thread.get('turns', []) for item in turn.get('items', [])
                if item['type'] in ('userMessage', 'agentMessage')]
    target = next((item for item in messages if item['id'] == message_id), None)
    if target is None:
        raise ValueError('Message is no longer available')
    if edit and target != next((m for m in reversed(messages) if m['type'] == 'userMessage'), None):
        raise ValueError('Only the latest user message can be edited')
    # Legacy item ids are generated by the history reader. Verify the entire
    # visible event sequence before using its ordinal (fail closed on compaction
    # or an unfamiliar rollout format, including repeated identical messages).
    lines = Path(thread['path']).read_text().splitlines(keepends=True)
    events = [(index, row['payload']) for index, line in enumerate(lines)
              for row in [json.loads(line)] if row['type'] == 'event_msg'
              and row['payload'].get('type') in ('user_message', 'agent_message')]
    kinds = {'userMessage': 'user_message', 'agentMessage': 'agent_message'}
    if [p['type'] for _, p in events] != [kinds[m['type']] for m in messages]:
        raise ValueError('Cannot safely locate this message in the saved conversation')
    found, event = events[messages.index(target)]
    kind = kinds[target['type']]
    event_text = json.loads(lines[found])['payload'].get('message', '')
    expected = target.get('text', '') if kind == 'agent_message' else '\n'.join(
        p.get('text', '') for p in target.get('content', []) if p.get('type') == 'text')
    if event_text.strip() != expected.strip():
        raise ValueError('Saved history has changed; reload the conversation and try again')
    stop = found + 1
    if edit:
        # The model-visible user response precedes its UI event. Exclude both.
        for index in range(found - 1, -1, -1):
            row = json.loads(lines[index])
            if row['type'] == 'response_item' and row['payload'].get('role') == 'user':
                stop = index
                break
        else:
            raise ValueError('Cannot safely locate the original input')
    # Codex owns creation/identity of the fork. Only the temporary input is cut;
    # the original rollout and any tools' external effects are left untouched.
    with tempfile.NamedTemporaryFile(mode='w', suffix='.jsonl', encoding='utf-8') as snapshot:
        snapshot.writelines(lines[:stop])
        snapshot.flush()
        result = session.rpc('thread/fork', {
            **session.thread_params({}), 'threadId': thread['id'],
            'path': snapshot.name, 'excludeTurns': False, 'deferGoalContinuation': True,
        })
    return result
